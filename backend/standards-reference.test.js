const assert = require('node:assert/strict')
const { analysisDocuments, referenceContext } = require('./standards-reference')
const { researchDocuments, buildSourceStatus } = require('./source-context')

const proposal = { location: 'Ogden, UT', name: 'Conduit and Vaults', text_content: 'Directional bore for telecommunications conduit. Minimum cover, utility offsets, equipment locations, permits and restoration.' }
const documents = analysisDocuments([])
const selected = researchDocuments(documents, proposal)
const status = buildSourceStatus(documents, proposal)
assert.ok(status.cityDocumentCount >= 55, 'Municipal inventory must work on an unseeded database')
assert.ok(selected.some(doc => new URL(doc.sourceUrl).hostname === 'www.ogdencity.gov'))
assert.ok(!selected.some(doc => /North Ogden|South Ogden/.test(doc.jurisdiction)))
assert.equal(status.referenceSources[0].pageCount, 192)
const references = referenceContext(selected, proposal)
assert.equal(references.length, 1)
for (const page of [83, 84, 85, 86]) assert.ok(references[0].pages.some(item => item.page === page), `Directional bore page ${page} must be included`)
const depth = references[0].pages.find(page => page.page === 84)
assert.match(depth.text, /Minimum allowable cover[\s\S]*24 inches/)
assert.match(depth.text, /Sanitary Sewer Main & Water Main: 10 feet/)
assert.match(depth.text, /No vaults, handholes[\s\S]*City sidewalk/)
assert.equal(referenceContext(researchDocuments(documents, { location: 'North Ogden, UT' }), proposal).length, 0)
const changed = analysisDocuments([{ ...selected[0], notes: 'Stored extraction takes precedence' }])
assert.equal(changed.find(doc => doc.id === selected[0].id).notes, 'Stored extraction takes precedence')
assert.equal(analysisDocuments([{id:'private',sensitivity:'restricted'}]).some(doc => doc.id === 'private'), false)
const small = referenceContext(selected, proposal, { maxPages:5, maxChars:16000 })
assert.ok(small[0].pages.length <= 5)
assert.ok(small[0].pages.reduce((sum,page)=>sum+page.text.length,0) <= 16000)
const dense = referenceContext(selected, { ...proposal, text_content: selected.find(doc=>doc.referencePages)?.referencePages.slice(10,70).map(page=>page.text).join('\n') + '\nDirectional bore telecom conduit' }, { maxPages:18, maxChars:16000 })
assert.ok(dense[0].pages.some(page=>page.page === 84), 'A tight budget must retain the directly relevant bore chapter ahead of generic earlier pages')
console.log('Official standards: unseeded catalog, exact city, cited page retrieval, scope isolation and prompt bounds: ok')
